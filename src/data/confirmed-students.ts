/**
 * Validates whether a given CNF string is authorized.
 */
export function getConfirmedStudent(cnfInput: string): ConfirmedStudent | null {
  if (!cnfInput) return null;
  const normalized = cnfInput.trim().toUpperCase();
  const name = CONFIRMED_STUDENTS_MAP[normalized];
  if (!name) return null;
  return { cnf: normalized, name };
}

/**
 * Validates credentials where password MUST match the CNF number.
 */
export function verifyConfirmedStudentCredentials(cnfInput: string, passwordInput: string): ConfirmedStudent | null {
  const student = getConfirmedStudent(cnfInput);
  if (!student) return null;
  if (passwordInput.trim().toUpperCase() !== student.cnf) return null;
  return student;
}
