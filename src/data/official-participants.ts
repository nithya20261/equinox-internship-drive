const PARTICIPANT_BY_CNF = new Map<string, OfficialParticipant>();
const PARTICIPANT_BY_EMAIL = new Map<string, OfficialParticipant>();

for (const p of OFFICIAL_PARTICIPANTS) {
  if (p.cnf) {
    PARTICIPANT_BY_CNF.set(p.cnf.toUpperCase(), p);
  }
  if (p.email) {
    PARTICIPANT_BY_EMAIL.set(p.email.toLowerCase(), p);
  }
}

/**
 * Lookup an official participant by Confirmation Number (CNF).
 */
export function getOfficialParticipantByCnf(cnf: string): OfficialParticipant | undefined {
  if (!cnf) return undefined;
  return PARTICIPANT_BY_CNF.get(cnf.trim().toUpperCase());
}

/**
 * Lookup an official participant by registered Email.
 */
export function getOfficialParticipantByEmail(email: string): OfficialParticipant | undefined {
  if (!email) return undefined;
  return PARTICIPANT_BY_EMAIL.get(email.trim().toLowerCase());
}
